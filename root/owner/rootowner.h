#ifndef ROOTOWNER_H
#define ROOTOWNER_H
// The resident Owner process and its console session (SafeOS kernel only).
// Include after types.h.
struct psinfo;
extern volatile int owner_chord;   // set by the keyboard path (kbd.c); consumed by consoleintr
extern volatile int owner_active;  // 1 while a session has the console (console.c, under cons.lock)
void owner_init(void);             // main.c: create the Owner process, after userinit()
void owner_request(void);          // console.c: wake the Owner; cons.lock must not be held
int  rootpool_exposure(int *total);   // proc.c: how many page tables map the Owner pool
int  ps_snapshot(struct psinfo *out);   // pskernel.c: fill a snapshot, kernel side
void owner_console_close(void);    // console.c: give the keyboard and screen back
int  owner_console_getc(void);     // console.c: one key, or -1 if none within about one timer tick
void owner_putc(int c);            // console.c: one output character; '\b' erases
struct inode;
extern uint owner_dir_inum;        // inode number of /owner, 0 = guard off
int  owner_guard_denies(struct inode *ip);                       // fs.c namex: 1 = hide this inode
int  owner_guard_denies_name(struct inode *parent, char *name);  // fs.c namex: 1 = refuse this name
void owner_fs_up(void);            // rootguard.c: create and guard /owner (called by root_fs_up)
void root_confirm(void);          // rootconfirm.c: record stage confirmed
void root_fs_up(void);            // rootfsup.c: the one call forkret makes once the file system is up
extern volatile int owner_fs_ready;   // 1 once /owner and the rules file are set up (rootguard.c)
void owner_rules_boot(void);          // rootrules.c: load /owner/rules at boot
int  rules_save_file(void);           // rootrules.c: write /owner/rules; 0 = ok
void owner_console_busy(int v);       // console.c: 1 = ignore chords while the Owner writes its files
struct trapframe;
void owner_gate(struct trapframe *tf);   // rootring1.c: gate 65
int  ring1_fault(struct trapframe *tf);  // rootring1.c: a fault at Ring 1
void owner1_fault(struct trapframe *tf);   // rootring1.c: a fault in the Ring 1 Owner: restart it
#define OWNER1_STACK_TOP   0x00100000    // top of the Ring 1 Owner's stack (virtual address)
#define OWNER1_STACK_PAGES 4
#define OWNER1_STACK_LO    (OWNER1_STACK_TOP - OWNER1_STACK_PAGES * 4096)
#define OWNER1_MAX_IMAGE   (64 * 4096)   // largest Owner image: 256 KB
void owner1_proc_create(void);            // proc.c: create the Owner as a Ring 1 process
#define PK_TOOL  0               // provider table kinds (rootgroups.c)
#define PK_APP   1
#define PK_AGENT 2
#define PK_SYSTEM 3              // init, and only as pid 1
int provider_kind(char *name);   // rootgroups.c: a program the provider does not list is an AI agent
int kill_group(int gid);         // proc.c: kill every process of a group; -2 for System, -1 for no such group
// ---- program identity (rootregistry.c; preinstalled.c is generated by genreg.pl) ----
struct inode;
struct reg_view;
struct prog_entry {
  uchar hash[32];            // SHA-256 of the whole program file
  char  name[16];
  int   kind;                // PK_*
};
extern const struct prog_entry preinstalled[];
extern const int npreinstalled;
int  registry_exec_check(struct inode *ip, char *name, char *regname);   // exec, with ip locked: -1 = do not start the program; regname gets the registered name, or ""
int  registry_mode(void);
int  registry_set_mode(int m);                            // -1 for a mode that does not exist
int  registry_entry(int idx, struct reg_view *v);         // fills v; -1 past the end (v->total is still set)
void registry_snapshot(void);                             // remember the current mode as the saved one
void registry_restore(void);                              // go back to the remembered mode
int  registry_dirty(void);                                // 1 if the mode differs from the remembered one
struct inst_view;
void registry_inst_read(struct inst_view *v);            // reads /inbox/<app>/ for the Owner: fills v, never sleeps on the log

void registry_apps_boot(void);                            // boot: load /owner/apps, apply the apps' rules, remove what /apps holds without a record
int  registry_app_kind(char *name);                       // PK_APP or PK_AGENT for an installed app, PK_AGENT for any other name
struct inst_req;
void registry_inst_commit(struct inst_req *q);            // the Owner, after the session has closed: copy, verify, record
int  apps_guard_has(uint inum);                          // 1 if the inode is an installed app's directory or file, or /apps
struct uninst_req;
void registry_uninstall(struct uninst_req *q);            // the Owner, after the session has closed: record, rules, processes, files
int  apps_report_hidden(uint inum);                       // 1 if inum is an app's report directory or file and the caller is not in that app's group
int  apps_report_is(uint inum);                           // 1 if inum is any app's report directory or file
struct rep_view;
void registry_report_read(struct rep_view *v);            // for the Owner: an app's header and text
int  apps_rules_dirty(void);                         // unsaved program rules, not counting the rows of installed apps
struct program_policy;
void apps_rules_export(struct program_policy *out);       // the program rules as saved: without the rows of installed apps
void registry_apps_reapply(void);                         // after a revert: every installed app's rules are its manifest's again
int  bin_guard_has(uint inum);                            // 1 if the inode is /bin, something in it, or /init: sealed against changes
int  bin_guard_dir(uint inum);                            // 1 if the inode is the /bin directory itself
void bin_guard_boot(void);                                // boot, before the guard is on: note the inodes in /bin, and /init
#endif
