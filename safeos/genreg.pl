#!/usr/bin/perl
# Writes preinstalled.c: the SHA-256 of each built program listed in providers.list.
# usage: genreg.pl [--dev] providers.list > preinstalled.c
use strict;
use warnings;
use Digest::SHA qw(sha256_hex);

my $dev = 0;
if(@ARGV && $ARGV[0] eq '--dev'){ $dev = 1; shift @ARGV; }
my $list = shift @ARGV or die "usage: genreg.pl [--dev] providers.list\n";
open(my $fh, '<', $list) or die "genreg: cannot open $list: $!\n";
my %kindname = (system => 'PK_SYSTEM', tool => 'PK_TOOL', app => 'PK_APP', agent => 'PK_AGENT');
my @entries;
while(my $line = <$fh>){
  $line =~ s/#.*//;
  $line =~ s/^\s+//;
  $line =~ s/\s+$//;
  next if $line eq '';
  my ($name, $kind, $flag) = split /\s+/, $line;
  die "genreg: bad line in $list: $line\n" unless defined $kind && exists $kindname{$kind};
  next if defined $flag && $flag eq 'dev' && !$dev;
  my $file = "_$name";
  unless(-f $file){ warn "genreg: $file is not built, so $name is not listed\n"; next; }
  open(my $bf, '<:raw', $file) or die "genreg: cannot read $file: $!\n";
  my $data = do { local $/; <$bf> };
  close $bf;
  push @entries, [$name, $kind, sha256_hex($data)];
}
my %rank = (system => 0, tool => 1, app => 2, agent => 3);   # System first, then Utilities, App, Agent
@entries = sort { $rank{$a->[1]} <=> $rank{$b->[1]} || $a->[0] cmp $b->[0] } @entries;   # each kind in name order
print "// Generated by genreg.pl from providers.list: do not edit.\n";
print "#include \"types.h\"\n#include \"defs.h\"\n#include \"rootowner.h\"\n\n";
print "const struct prog_entry preinstalled[] = {\n";
for my $e (@entries){
  my ($name, $kind, $hex) = @$e;
  my @bytes = map { '0x' . substr($hex, $_ * 2, 2) } 0 .. 31;
  printf "  { { %s },\n    \"%s\", %s },\n", join(', ', @bytes), $name, $kindname{$kind};
}
print "};\nconst int npreinstalled = ", scalar(@entries), ";\n";
